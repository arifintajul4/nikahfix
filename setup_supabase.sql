-- Buat tabel nikahfix untuk menyimpan ucapan/pesan
CREATE TABLE IF NOT EXISTS public.nikahfix (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  message TEXT NOT NULL,
  name TEXT NOT NULL,
  color TEXT NOT NULL
);

-- Mengaktifkan Row Level Security (RLS) agar data aman
ALTER TABLE public.nikahfix ENABLE ROW LEVEL SECURITY;

-- Membuat Policy agar siapapun (anonim) bisa membaca ucapan/pesan
CREATE POLICY "Allow public read access" 
ON public.nikahfix
FOR SELECT 
USING (true);

-- Membuat Policy agar siapapun (anonim) bisa mengirim ucapan/pesan
CREATE POLICY "Allow public insert access" 
ON public.nikahfix
FOR INSERT 
WITH CHECK (true);
